/**
 * Generates an ISO string offset by given days and hours from current moment.
 * Ensures demo deadlines dynamically showcase all 5 deadline states reliably.
 */
function createRelativeDate(daysOffset: number, hoursOffset: number = 0): string {
  const d = new Date()
  d.setDate(d.getDate() + daysOffset)
  d.setHours(d.getHours() + hoursOffset)
  return d.toISOString()
}

